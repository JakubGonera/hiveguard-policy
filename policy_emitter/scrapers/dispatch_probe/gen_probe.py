#!/usr/bin/env python3
"""Emit probe.bt with one kretprobe block per attachable dispatcher.

Why generated rather than hand-written:

1. The kernel's set of "actually-traceable" dispatchers varies by build
   (functions in kernel/trace/bpf_trace.c, net/smc, drivers/media/rc lose
   their ftrace prologue via `ccflags-remove $(CC_FLAGS_FTRACE)` and become
   unattachable). We filter against the kernel's own list of traceable
   functions at /sys/kernel/tracing/available_filter_functions.

2. bpftrace 0.20's `probe` builtin requires the multi-probe block to be
   homogeneously attachable; one unattachable probe aborts the WHOLE block.
   We sidestep this by writing one kretprobe block per dispatcher with the
   name as a literal in the printf, so an attach failure only affects that
   one block.

Usage: gen_probe.py [--out probe.bt]
"""

import argparse
import sys

# Master list of dispatchers — anything assigned to `.get_func_proto` in a
# `struct bpf_verifier_ops` instance, plus the chained-fallback dispatchers.
# Sourced from net/core/filter.c, kernel/trace/bpf_trace.c, kernel/bpf/*,
# net/ipv4/tcp_ipv4.c, net/unix/af_unix.c, net/ipv4/bpf_tcp_ca.c,
# net/smc/bpf_smc.c, drivers/media/rc/bpf-lirc.c.
CANDIDATES = [
    "bpf_base_func_proto",
    "bpf_sk_base_func_proto",
    "bpf_tracing_func_proto",       # tracing-family shared fallback
    "bpf_lsm_func_proto",
    "bpf_nf_func_proto",
    "bpf_smc_hs_func_proto",
    "bpf_tcp_ca_get_func_proto",
    "bpf_iter_tcp_get_func_proto",
    "bpf_iter_unix_get_func_proto",
    "cg_skb_func_proto",
    "cg_sockopt_func_proto",
    "cgroup_dev_func_proto",
    "flow_dissector_func_proto",
    "kprobe_prog_func_proto",
    "lirc_mode2_func_proto",
    "lwt_in_func_proto",
    "lwt_out_func_proto",
    "lwt_xmit_func_proto",
    "lwt_seg6local_func_proto",
    "pe_prog_func_proto",
    "raw_tp_prog_func_proto",
    "sk_filter_func_proto",
    "sk_lookup_func_proto",
    "sk_msg_func_proto",
    "sk_reuseport_func_proto",
    "sk_skb_func_proto",
    "sock_addr_func_proto",
    "sock_filter_func_proto",
    "sock_ops_func_proto",
    "syscall_prog_func_proto",
    "sysctl_func_proto",
    "tc_cls_act_func_proto",
    "tp_prog_func_proto",
    "tracing_prog_func_proto",
    "xdp_func_proto",
]

# Paths checked in order; we read the first one that exists.
AVAILABLE_FUNCS_PATHS = [
    "/sys/kernel/tracing/available_filter_functions",
    "/sys/kernel/debug/tracing/available_filter_functions",
]

HEADER = '''\
#!/usr/bin/env bpftrace
/*
 * GENERATED by gen_probe.py — do not edit. Regenerate with:
 *     ./gen_probe.py --out probe.bt
 *
 * Attach at every per-program-type helper-proto dispatcher that the kernel
 * exposes as traceable. All dispatchers share the signature
 *   const struct bpf_func_proto *fn(enum bpf_func_id, const struct bpf_prog *)
 * so arg0 == func_id, arg1 == prog, retval == proto pointer (or NULL).
 *
 * Fallback chains (xdp_func_proto -> bpf_sk_base_func_proto ->
 * bpf_base_func_proto) recurse on the same thread; a per-tid depth counter
 * pairs entries with their returns in strict LIFO order. depth=1 is the
 * outermost dispatcher and its return value is what the verifier ultimately
 * binds.
 *
 * Return-side handlers are emitted one per dispatcher with the name as a
 * literal — keeps bpftrace 0.20 from aborting a whole comma-block when one
 * probe fails to generate code.
 */

BEGIN
{
    printf("# probe attached (filter comm=proto_drv)\\n");
}

'''

ENTRY_TEMPLATE = '''\
{entry_list}
/comm == "proto_drv"/
{{
    @depth[tid]++;
    $d = @depth[tid];
    @a0[tid, $d] = arg0;
    @a1[tid, $d] = arg1;
}}

'''

RETURN_TEMPLATE = '''\
kretprobe:{name}
/@depth[tid] > 0/
{{
    $d    = @depth[tid];
    $prog = (struct bpf_prog *)@a1[tid, $d];
    $fid  = (int32)@a0[tid, $d];
    printf("EV disp={name} d=%d pt=%d fid=%d addr=0x%lx\\n",
           $d, $prog->type, $fid, retval);
    delete(@a0[tid, $d]);
    delete(@a1[tid, $d]);
    @depth[tid]--;
}}

'''

FOOTER = '''\
END
{
    clear(@depth); clear(@a0); clear(@a1);
    printf("# probe detached\\n");
}
'''

def _load_traceable() -> set[str] | None:
    """Return the set of function names ftrace can attach to, or None if
    the filter list isn't readable (e.g. tracefs not mounted)."""
    for path in AVAILABLE_FUNCS_PATHS:
        try:
            with open(path) as f:
                names: set[str] = set()
                for line in f:
                    # Lines look like "func_name" or "func_name [module]".
                    tok = line.split(None, 1)[0].strip()
                    if tok:
                        names.add(tok)
                return names
        except (FileNotFoundError, PermissionError):
            continue
    return None

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="probe.bt")
    args = ap.parse_args()

    traceable = _load_traceable()
    if traceable is None:
        print("gen_probe: warning: no available_filter_functions; "
              "emitting all candidates (bpftrace will warn/skip)",
              file=sys.stderr)
        attachable = list(CANDIDATES)
        skipped: list[str] = []
    else:
        attachable = [n for n in CANDIDATES if n in traceable]
        skipped    = [n for n in CANDIDATES if n not in traceable]

    if not attachable:
        sys.exit("gen_probe: no candidate dispatchers attachable on this kernel")

    print(f"gen_probe: {len(attachable)} attachable, "
          f"{len(skipped)} skipped", file=sys.stderr)
    if skipped:
        print(f"  skipped: {', '.join(skipped)}", file=sys.stderr)

    entry_list = ",\n".join(f"kprobe:{n}" for n in attachable)

    parts = [
        HEADER,
        ENTRY_TEMPLATE.format(entry_list=entry_list),
    ]
    for name in attachable:
        parts.append(RETURN_TEMPLATE.format(name=name))
    parts.append(FOOTER)

    with open(args.out, "w") as f:
        f.write("".join(parts))
    print(f"gen_probe: wrote {args.out}", file=sys.stderr)
    return 0

if __name__ == "__main__":
    sys.exit(main())
