"""PTR_TO_CTX access predicates from ctx_layouts.json."""

from __future__ import annotations

import json
from pathlib import Path

from pdsl.ast import (
    Add,
    And,
    BoolLit,
    Comparison,
    Equality,
    Expr,
    Field,
    GlobalPredicate,
    Hole,
    Implication,
    IntLit,
    Mod,
    Or,
    PolicyFile,
    PredicateCall,
    Prop,
    Static,
    TypeJudgment,
    Var,
)
from pdsl.format_pol import format_policy_file

_CTX_LAYOUTS = (
    Path(__file__).parent.parent / "scrapers" / "contexts" / "ctx_layouts.json"
)
_DEBUG_OUT = Path(__file__).parent.parent / "ctx_access.debug.pol"

_ACCESS_PARAMS = ["off", "size"]
_OFF, _SIZE = Var("off"), Var("size")

_BANNER = (
    "# ====================================================================\n"
    "# AUTO-GENERATED by ebpf/ctx_emitter.py - DO NOT EDIT BY HAND.\n"
    "# Debug view of the PTR_TO_CTX access predicates merged into policies.pol.\n"
    "# TRACING/LSM/STRUCT_OPS/EXT are holes: ctx is BTF/attach-determined, not a\n"
    "# static layout.\n"
    "# Regenerate: uv run python -m ebpf.cli generate\n"
    "# ====================================================================\n"
)


def _conjoin(exprs: list[Expr]) -> Expr:
    acc = exprs[0]
    for e in exprs[1:]:
        acc = And(acc, e)
    return acc


def _disjoin(exprs: list[Expr]) -> Expr:
    acc = exprs[0]
    for e in exprs[1:]:
        acc = Or(acc, e)
    return acc


def _access_pred_name(prog_type: str, direction: str) -> str:
    return prog_type[len("BPF_PROG_TYPE_") :].lower() + f"_ctx_{direction}_access"


def _dir_guard(d: dict | None) -> Expr:
    if not d or not d.get("access_sizes"):
        return Prop(BoolLit(False))
    parts: list[Expr] = [
        _disjoin([Equality(_SIZE, IntLit(s)) for s in d["access_sizes"]])
    ]
    if d.get("attach_type"):
        parts.append(
            _disjoin([Equality(Var("ATTACH_TYPE"), Var(a)) for a in d["attach_type"]])
        )
    parts += [PredicateCall("CAPABILITY", [Var(c)]) for c in d.get("capability", [])]
    if d.get("offloaded"):
        parts.append(PredicateCall("OFFLOADED", []))
    return _conjoin(parts)


def _row_term(row: dict, direction: str) -> Expr:
    base, size = row["offset"], row["size"]
    parts: list[Expr] = [
        Comparison(IntLit(base), "<=", _OFF),
        Comparison(Add(_OFF, _SIZE), "<=", IntLit(base + size)),
    ]
    if row.get("interior", True) is False:
        parts.append(Equality(_OFF, IntLit(base)))
    parts.append(_dir_guard(row[direction]))
    return _conjoin(parts)


def _pt_access_predicate(prog_type: str, rows: list[dict], direction: str) -> GlobalPredicate:
    body = And(
        Equality(Mod(_OFF, _SIZE), IntLit(0)),
        _disjoin([_row_term(r, direction) for r in rows]),
    )
    return GlobalPredicate(_access_pred_name(prog_type, direction), list(_ACCESS_PARAMS), body)


def _ctx_access(layouts: dict, direction: str) -> GlobalPredicate:
    # Unmodeled prog types (null layout) stay a hole, so an access under them is
    # an undischarged obligation rather than a silent pass.
    branches = []
    for prog_type, rows in layouts.items():
        cond = Equality(Var("PROG_TYPE"), Var(prog_type))
        if rows is None:
            branches.append(Implication(cond, Hole()))
        else:
            branches.append(
                Implication(cond, PredicateCall(_access_pred_name(prog_type, direction), [_OFF, _SIZE]))
            )
    return GlobalPredicate(f"ctx_{direction}_access", list(_ACCESS_PARAMS), _conjoin(branches))


# --- ctx_read_type: the result type of a PTR_TO_CTX load (kernel info.reg_type) ---
# ctx_read_access/ctx_write_access validate *whether* a field access is legal; this family
# says what type the destination register receives. The map (prog_type, offset) -> type is static
# (ctx_layouts.json row["type"]), so it is a conjunction of `range -> dst : <type>`.

_READ_TYPE_PARAMS = ["dst", "off", "size"]
_DST = Var("dst")

# Pointer result types carry a fixed-zero offset (kernel mark_reg_known_zero).
_PTR_RESULTS = {
    "PTR_TO_PACKET",
    "PTR_TO_PACKET_END",
    "PTR_TO_PACKET_META",
    "PTR_TO_SOCKET",
    "PTR_TO_SOCKET_OR_NULL",
    "PTR_TO_SOCK_COMMON_OR_NULL",
    "PTR_TO_FLOW_KEYS",
    "PTR_TO_TP_BUFFER",
    "PTR_TO_BTF_ID_TRUSTED",
}


def _read_type_pred_name(prog_type: str) -> str:
    return prog_type[len("BPF_PROG_TYPE_") :].lower() + "_ctx_read_type"


def _row_type_term(row: dict) -> Expr:
    base, size, t = row["offset"], row["size"], row["type"]
    rng = And(
        Comparison(IntLit(base), "<=", _OFF),
        Comparison(Add(_OFF, _SIZE), "<=", IntLit(base + size)),
    )
    concl: Expr = TypeJudgment(_DST, t)
    if t in _PTR_RESULTS:
        concl = And(concl, Equality(Field(_DST, "offset"), IntLit(0)))
        if t == "PTR_TO_BTF_ID_TRUSTED":
            # btf_id is kernel/BTF-specific and not in the scrape; resolve it at
            # verification time rather than leaving it free (which would be unsound).
            concl = And(concl, Equality(Field(_DST, "btf_id"), Static("ctx_field_btf_id(off)")))
    return Implication(rng, concl)


def _pt_read_type_predicate(prog_type: str, rows: list[dict]) -> GlobalPredicate:
    body = _conjoin([_row_type_term(r) for r in rows])
    return GlobalPredicate(_read_type_pred_name(prog_type), list(_READ_TYPE_PARAMS), body)


def _ctx_read_type(layouts: dict) -> GlobalPredicate:
    # Same hole discipline as ctx_read_access: a read under a BTF/attach-determined
    # ctx (null layout) leaves the result type as an undischarged obligation.
    branches = []
    for prog_type, rows in layouts.items():
        cond = Equality(Var("PROG_TYPE"), Var(prog_type))
        if rows is None:
            branches.append(Implication(cond, Hole()))
        else:
            branches.append(
                Implication(cond, PredicateCall(_read_type_pred_name(prog_type), [_DST, _OFF, _SIZE]))
            )
    return GlobalPredicate("ctx_read_type", list(_READ_TYPE_PARAMS), _conjoin(branches))


def build_ctx_predicates(data_dir: Path | None = None) -> list[GlobalPredicate]:
    path = _CTX_LAYOUTS if data_dir is None else data_dir / "contexts" / "ctx_layouts.json"
    layouts = json.loads(path.read_text())
    preds: list[GlobalPredicate] = []
    for pt, rows in layouts.items():
        if rows is not None:
            preds.append(_pt_access_predicate(pt, rows, "read"))
            preds.append(_pt_access_predicate(pt, rows, "write"))
            preds.append(_pt_read_type_predicate(pt, rows))
    preds.append(_ctx_access(layouts, "read"))
    preds.append(_ctx_access(layouts, "write"))
    preds.append(_ctx_read_type(layouts))
    return preds


def write_debug_file(
    predicates: list[GlobalPredicate], out_path: Path | None = None
) -> Path:
    out_path = out_path or _DEBUG_OUT
    pf = PolicyFile(predicates=predicates, prologue=None, policies=[])
    out_path.write_text(_BANNER + "\n" + format_policy_file(pf))
    return out_path
